import { expect, test, type Page } from '@playwright/test'
test.setTimeout(90000)
const U='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',V='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb'
async function navegarSecao(raiz: Page | import('@playwright/test').Locator, label: string) { const sel=raiz.getByRole('combobox',{name:'Seção',exact:true}); if(await sel.isVisible())await sel.selectOption({label}); else await raiz.getByRole('navigation',{name:'Seções da ficha'}).getByRole('button',{name:label,exact:true}).click(); }
async function abrir(page:Page, escuro=false) {
  await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort())
  await page.goto('/tests/operacional/equipe-fichas-demo.html')
  await expect(page.getByRole('button',{name:'Ver cadastro de Médico CLT Sintético',exact:true})).toBeVisible({timeout:60000})
  if (escuro) await page.getByRole('button',{name:'Ativar modo escuro'}).click()
  await page.getByRole('button',{name:'Ver cadastro de Médico CLT Sintético',exact:true}).click()
  await navegarSecao(page,'Atuação e atendimentos')
  const s=page.locator('[data-ficha-secao="atuacao"]')
  await expect(s.getByText('30 min · configuração do profissional, compartilhada entre suas clínicas.')).toBeVisible()
  return s
}
async function controle(page:Page,falha:string) { await page.evaluate(falha=>window.dispatchEvent(new CustomEvent('controle-demo-atuacao',{detail:{falha}})),falha) }
test('fontes por unidade, ausência, contexto e responsividade',async({page},info)=>{
  const s=await abrir(page)
  await expect(s).toContainText('R$ 180,00')
  await expect(s).toContainText('20% · regra da clínica')
  await expect(s.getByRole('button',{name:'Configurar serviços — indisponível'})).toBeDisabled()
  await s.getByRole('combobox',{name:'Clínica da atuação'}).selectOption(V)
  await expect(s).toContainText('R$ 240,00')
  await expect(s).toContainText('25% · regra da clínica')
  await expect(s).toContainText('Sem horário habitual cadastrado')
  await s.getByText('Catálogo existente desta clínica (0)',{exact:true}).click()
  await expect(s.getByText('Nenhum serviço ativo nesta clínica.')).toBeVisible()
  await expect(page.getByRole('combobox',{name:'Selecionar clínica',exact:true})).toHaveValue(U)
  await expect(page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).resolves.toBe(true)
  await page.screenshot({path:`scratch/equipe-atuacao/${info.project.name}.png`})
  await page.getByRole('dialog').getByRole('button',{name:'Fechar',exact:true}).click()
  await page.getByLabel('Buscar por nome, cargo ou profissão').fill('Médico CLT')
  await page.getByRole('button',{name:'Ver cadastro de Médico CLT Sintético',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Fechar',exact:true}).click()
  await expect(page.getByLabel('Buscar por nome, cargo ou profissão')).toHaveValue('Médico CLT')
})
test('preço persiste sinteticamente por clínica e duração é compartilhada',async({page})=>{
  let s=await abrir(page)
  await s.getByRole('button',{name:'Editar preço nesta clínica',exact:true}).click()
  await s.getByLabel('Preço nesta clínica (R$)').fill('199,90')
  await s.getByRole('button',{name:'Salvar configuração'}).click()
  await expect(s).toContainText('R$ 199,90')
  await s.getByRole('combobox',{name:'Clínica da atuação'}).selectOption(V)
  await expect(s).toContainText('R$ 240,00')
  await s.getByRole('button',{name:'Editar duração da Agenda'}).click()
  await s.getByLabel('Duração compartilhada (minutos)').fill('40')
  await s.getByRole('button',{name:'Salvar configuração'}).click()
  await expect(s).toContainText('40 min · configuração do profissional')
  await page.getByRole('dialog').getByRole('button',{name:'Fechar',exact:true}).click()
  await page.reload()
  await page.getByRole('button',{name:'Ver cadastro de Médico CLT Sintético',exact:true}).click()
  await navegarSecao(page,'Atuação e atendimentos')
  s=page.locator('[data-ficha-secao="atuacao"]')
  await expect(s).toContainText('R$ 199,90')
  await expect(s).toContainText('40 min · configuração do profissional')
})
