test('modo escuro e backend ausente mantêm estados claros; logout ignora resposta atrasada',async({page})=>{
  const s=await abrir(page,true)
  await controle(page,'PGRST202')
  await s.getByRole('button',{name:'Reconsultar atuação'}).click()
  await expect(s).toContainText('Atuação indisponível neste ambiente')
  await expect(s.getByRole('button',{name:'Editar duração da Agenda'})).toHaveCount(0)
  await controle(page,'')
  await s.getByRole('button',{name:'Reconsultar atuação'}).click()
  await expect(s).toContainText('R$ 180,00')
  await page.evaluate(()=>window.dispatchEvent(new CustomEvent('controle-demo-atuacao',{detail:{atraso:true}})))
  await s.getByRole('button',{name:'Reconsultar atuação'}).click()
  await page.evaluate(async()=>{const {supabase}=await import('/src/lib/supabase.ts');await supabase.auth.signOut({scope:'local'})})
  await page.evaluate(()=>window.dispatchEvent(new Event('liberar-demo-atuacao')))
  await expect(page.locator('[data-ficha-secao="atuacao"]')).toHaveCount(0)
  await expect(page.getByRole('dialog').getByRole('button',{name:'Fechar',exact:true})).toBeEnabled()
})
