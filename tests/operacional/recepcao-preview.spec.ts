import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

const url = '/tests/operacional/recepcao-preview.html'
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => { if (!localStorage.getItem('clinica-patricia:tema')) localStorage.setItem('clinica-patricia:tema', 'claro'); localStorage.removeItem('clinica:sidebar:expanded') })
  await page.route('https://**/*', route => route.abort())
})
async function abrir(page: import('@playwright/test').Page, query = '') {
  await page.goto(url + query, { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: 'Movimento de hoje' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Atualizar', exact: true })).toBeEnabled()
}
async function captura(page: import('@playwright/test').Page, nome: string) {
  await mkdir('scratch/recepcao-preview/capturas', { recursive: true })
  await page.screenshot({ path: `scratch/recepcao-preview/capturas/${nome}.png`, fullPage: true })
}
test('composição, espera por chegada, estados oficiais, temas e capturas', async ({ page }, info) => {
  const externas: string[] = []; const erros: string[] = []
  // O antivírus do Windows injeta requisições próprias; elas não são serviços da proposta.
  page.on('request', r => { const host = new URL(r.url()).hostname; if (!r.url().startsWith('http://127.0.0.1:4193') && !host.endsWith('.kaspersky-labs.com')) externas.push(r.url()) })
  page.on('pageerror', e => erros.push(e.message))
  await abrir(page)
  const indicadores = page.getByRole('region', { name: 'Indicadores do dia' })
  await expect(indicadores).toContainText('18'); await expect(indicadores).toContainText('3')
  await expect(page.getByTestId('registro')).toHaveCount(3)
  await expect(page.getByTestId('registro').first()).toContainText('25 min de espera')
  await expect(page.getByTestId('registro').last()).toContainText('Parcialmente estornado')
  await expect(page.getByTestId('registro').last().getByRole('button')).toHaveText('Conferir')
  await expect(page.getByText('18 agendamentos / 17 pacientes distintos', { exact: false })).toBeVisible()
  if (info.project.name !== 'desktop') {
    await expect(page.getByRole('button', { name: /Caixa do turno/ })).toHaveAttribute('aria-expanded', 'false')
    await expect(page.getByRole('button', { name: /Pendências cadastrais/ })).toHaveAttribute('aria-expanded', 'false')
  }
  const fila = await page.getByRole('heading', { name: 'Movimento de hoje' }).boundingBox()
  expect(fila!.y).toBeLessThan(info.project.name === 'mobile' ? 640 : 600)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await captura(page, `${info.project.name}-claro`)
  await page.getByRole('button', { name: 'Ativar modo escuro' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'escuro')
  await captura(page, `${info.project.name}-escuro`)
  await page.reload(); await expect(page.locator('html')).toHaveAttribute('data-theme', 'escuro')
  expect(externas).toEqual([]); expect(erros).toEqual([])
})
