test('resposta atrasada não reaparece após trocar clínica; desatualização explícita', async ({ page }) => {
  await abrir(page, '?atraso')
  await page.getByRole('button', { name: 'Atualizar', exact: true }).click()
  await page.getByText('Cenários de demonstração', { exact: true }).click()
  await page.getByLabel('Unidade simulada').selectOption('previa-ipupiara')
  await expect(page.getByTestId('registro')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Atualizar', exact: true })).toBeEnabled()
  await expect(page.getByTestId('registro').first()).toContainText('Ana Moura (I)')
  await page.getByLabel('Cenário da prévia').selectOption('desatualizado')
  await expect(page.getByRole('button', { name: 'Atualizar', exact: true })).toBeEnabled()
  await expect(page.getByRole('heading', { name: 'Dados desatualizados', exact: true })).toBeVisible()
  await expect(page.getByTestId('registro').first()).toContainText('Espera indisponível')
  await page.getByRole('button', { name: 'Atualizar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dados desatualizados', exact: true })).toHaveCount(0)
})
