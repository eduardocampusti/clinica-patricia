test('B1: faixa e blocos ignoram o próprio registro, criação continua contando os três ocupados', async ({ page }, info) => {
  await abrir(page, 'remarcacao')
  await page.locator('[data-registro-id="ag-r"]').getByRole('button', { name: 'Editar agendamento' }).click()
  const painel = page.getByRole('dialog', { name: 'Remarcar agendamento' })
  await expect(painel.getByRole('group', { name: 'Próximos dias' }).getByRole('button').first()).toContainText('18 livres')
  const livres = painel.getByRole('group', { name: 'Horários disponíveis', exact: true }).getByRole('button').filter({ hasNot: page.locator('[disabled]') })
  expect(await livres.evaluateAll(els => els.filter(el => !(el as HTMLButtonElement).disabled).length)).toBe(18)
  await expect(painel.getByRole('group', { name: 'Horários disponíveis', exact: true }).getByRole('button', { name: '11:00', exact: true })).toBeEnabled()
  await painel.getByRole('group', { name: 'Próximos dias' }).scrollIntoViewIfNeeded()
  await captar(page, `b1-${info.project.name}`)
  await abrir(page, 'remarcacao')
  await page.getByRole('button', { name: '+ Novo agendamento', exact: true }).click()
  const novo = page.getByRole('dialog', { name: 'Novo agendamento' })
  await novo.locator('input[name="novo-agendamento-profissional"][value="prof-1"]').check()
  await expect(novo.getByRole('group', { name: 'Próximos dias' }).getByRole('button').first()).toContainText('17 livres')
})

test('B2: passados desabilitados, faixa e indicador coerentes; futuro intacto e Outro horário preservado', async ({ page }, info) => {
  await abrir(page, '', '10:20')
  await expect(page.getByRole('region', { name: 'Resumo do dia' }).locator(':scope > div').nth(3)).toContainText('15')
  await page.getByRole('button', { name: 'Dia', exact: true }).click()
  await expect(page.getByRole('button', { name: '08:00 horário já passou — Profissional Sintético — Clínica geral', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '+ Novo agendamento', exact: true }).click()
  const painel = page.getByRole('dialog', { name: 'Novo agendamento' })
  await painel.locator('input[name="novo-agendamento-profissional"][value="prof-1"]').check()
  const faixa = painel.getByRole('group', { name: 'Próximos dias' })
  await expect(faixa.getByRole('button').first()).toContainText('15 livres')
  const blocos = painel.getByRole('group', { name: 'Horários disponíveis', exact: true })
  const passado = blocos.getByRole('button', { name: '08:00 horário já passou', exact: true })
  await expect(passado).toBeDisabled()
  await expect(passado).toHaveCSS('opacity', '0.5')
  await expect(blocos.getByRole('button', { name: '10:00 horário já passou', exact: true })).toBeDisabled()
  await expect(blocos.getByRole('button', { name: '10:30', exact: true })).toBeEnabled()
  await faixa.scrollIntoViewIfNeeded()
  await captar(page, `b2-${info.project.name}`)
  await passado.scrollIntoViewIfNeeded()
  await captar(page, `b2-blocos-${info.project.name}`)
  await painel.getByRole('button', { name: 'Outro horário', exact: true }).click()
  await painel.getByLabel('Início', { exact: true }).fill('08:00')
  await expect(painel.getByLabel('Início', { exact: true })).toHaveValue('08:00')
  await faixa.getByRole('button').nth(1).click()
  await expect(faixa.getByRole('button').nth(1)).toContainText('20 livres')
  await expect(blocos.getByRole('button', { name: '08:00', exact: true })).toBeEnabled()
})
