test('aprovação e devolução de fechamento seguem perfil, sem nova abertura', async ({ page }) => {
  for (const decisao of ['aprovar', 'devolver']) {
    await abrir(page, 'aprovacao'); await page.getByText('Cenários de demonstração').click(); await page.getByLabel('Perfil simulado').selectOption('proprietaria')
    await page.getByRole('button', { name: 'Revisar fechamento', exact: true }).click(); await page.getByLabel('Decisão da proprietária').selectOption(decisao)
    if (decisao === 'devolver') await page.getByLabel('Observação / orientação').fill('Recontar as cédulas.')
    await page.getByRole('button', { name: 'Confirmar decisão' }).click(); await expect(page.getByText(/Fechamento (aprovado|devolvido para correção) no serviço sintético/).last()).toBeVisible()
    await page.getByRole('button', { name: 'Concluir demonstração' }).click()
    if (decisao === 'aprovar') await expect(page.getByLabel('Fundo inicial contado')).toHaveValue('')
    else await expect(page.getByText('Contagem devolvida pela proprietária')).toBeVisible()
  }
})

