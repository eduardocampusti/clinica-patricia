import { test, expect, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
const url = '/tests/financeiro/recepcao-preview.html'
test.beforeEach(async ({ page }) => {
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
})
async function abrir(page: Page, cenario = 'aberto') { await page.goto(`${url}?cenario=${cenario}`); await expect(page.getByRole('heading', { name: 'Caixa da recepção' })).toBeVisible() }
async function split(page: Page) {
  await page.getByRole('button', { name: '＋ Receber pagamento' }).click()
  await page.getByLabel('Dividir pagamento').check()
  await page.getByLabel('Dinheiro entregue pelo paciente').fill('150,00')
  await page.getByLabel('Conferi o Pix externamente').check()
}
test('composição coerente, proposta opcional, filtro e paginação', async ({ page }) => {
  await abrir(page)
  await expect(page.getByTestId('esperado')).toHaveText(/420,00/)
  await expect(page.getByTestId('recebido')).toHaveText(/900,00/)
  await expect(page.getByText('A receber hoje · proposta')).toHaveCount(0)
  await page.getByRole('button', { name: 'Próxima', exact: true }).click()
  await expect(page.getByText('Maria Exemplo')).toBeVisible()
  await page.getByLabel('Buscar movimentação').fill('Carla')
  await expect(page.getByText('Carla Exemplo')).toBeVisible()
  await expect(page.getByText('Pedro Exemplo')).toHaveCount(0)
})
test('split integral, troco, confirmação única e falha de impressão', async ({ page }) => {
  await abrir(page); await split(page)
  await expect(page.getByTestId('troco')).toHaveText(/50,00/)
  const enviar = page.getByRole('button', { name: /Registrar R\$.*220,00/ })
  // Dois eventos no mesmo ciclo devem passar pela trava antes de qualquer resposta.
  await enviar.evaluate((el: HTMLButtonElement) => { el.click(); el.click() })
  await expect(page.getByText('Recebimento de R$', { exact: false })).toHaveCount(0)
  await expect(page.getByText(/Recebimento de.*220,00 confirmado pelo serviço sintético/)).toBeVisible()
  await page.getByRole('button', { name: 'Imprimir recibo demonstrativo' }).click()
  await expect(page.getByText(/Impressão não concluída/)).toBeVisible()
  await page.getByRole('button', { name: 'Tentar impressão novamente' }).click()
  await expect(page.getByText(/Reimpressão simulada concluída/)).toBeVisible()
  await page.getByRole('button', { name: 'Concluir demonstração' }).click()
  await expect(page.getByTestId('recebido')).toHaveText(/1.120,00/)
  await expect(page.getByTestId('esperado')).toHaveText(/520,00/)
  await expect(page.getByText('Valor bruto de toda a sessão.')).toBeVisible()
})
